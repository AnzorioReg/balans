const {chromium}=require('playwright'),assert=require('node:assert/strict');
(async()=>{
 const b=await chromium.launch({headless:true,channel:'chromium'}),c=await b.newContext({viewport:{width:390,height:844}});
 await c.addInitScript(()=>{
  window.saves=[];window.healthCalls=[];
  window.BalansSave={save:(name,content,type)=>saves.push({name,content,type}),shareText:()=>{}};
  window.BalansHealth=Object.fromEntries(['status','sync','connect','disconnect','settings','install'].map(k=>[k,()=>healthCalls.push(k)]));
 });
 const p=await c.newPage(),errors=[];p.on('pageerror',e=>errors.push(e.message));
 await p.goto('file://'+__dirname+'/index.html');
 await p.evaluate(()=>{
  const ts=Date.now()-60000;
  state.deviceData={weight:[{id:'old',ts,v:85,source:'com.health'}],steps:[{ts,v:1200,day:localDay(ts),source:'com.health'}]};
  state.healthInfo.granted=['android.permission.health.READ_WEIGHT','android.permission.health.READ_STEPS'];
  state.bleData={heart:[{ts,v:70,source:'Bluetooth Test'}]};
  renderAll();openForm('weight');
 });
 await p.locator('#f [name=v]').fill('82,4');
 await p.locator('#f button[type=submit]').click();
 assert.equal(await p.evaluate('cur(byId.weight)'),82.4,'New manual measurement must be newer than prior HC reading today');
 assert.equal(await p.evaluate('state.manual.weight.rec.length'),1);
 await p.locator('#sheet [data-close]').click();
 await p.evaluate(()=>openForm('bp'));
 await p.locator('#f [name=v]').fill('80');
 await p.locator('#f [name=lo]').fill('120');
 await p.locator('#f button[type=submit]').click();
 assert.ok(await p.locator('#f .form-error').isVisible());
 assert.equal(await p.evaluate('state.manual.bp?.rec.length||0'),0);
 await p.locator('#f [name=v]').fill('122');
 await p.locator('#f [name=lo]').fill('81');
 await p.locator('#f button[type=submit]').click();
 assert.equal(await p.evaluate('recs(byId.bp).at(-1).lo'),81);
 await p.locator('#sheet [data-close]').click();
 await p.evaluate(()=>onHealthEvent({type:'permissions',granted:['android.permission.health.READ_STEPS'],message:'Права обновлены'}));
 assert.deepEqual(await p.evaluate('Object.keys(state.deviceData)'),['steps']);
 assert.equal(await p.evaluate('cur(byId.weight)'),82.4,'Permission revocation must not delete manual record');
 assert.equal(await p.evaluate('cur(byId.heart)'),70,'Permission revocation must not delete BLE');
 await p.evaluate(()=>onHealthEvent({type:'cancelled',message:'Чтение приостановлено'}));
 assert.deepEqual(await p.evaluate('Object.keys(state.deviceData)'),['steps'],'Cancelled read must preserve snapshot');
 await p.evaluate(()=>{state.metric='bp';state.period='week';state.cat='Все';setTab('dynamics');renderDynamics()});
 assert.ok((await p.locator('#dynCard .big').innerText()).includes('122/81'),'Dynamics must preserve both BP values');
 await p.evaluate(()=>renderHeat());
 assert.match(await p.locator('#heat i').last().getAttribute('title'),/показателей с записями: 4/);
 await p.evaluate(()=>go('export'));
 await p.locator('[data-x=csv]').click();
 const csv=await p.evaluate(()=>decodeURIComponent(escape(atob(saves.at(-1).content))));
 assert.ok(csv.includes('Health Connect · com.health'));
 assert.ok(csv.includes('Bluetooth Test'));assert.ok(csv.includes('Вручную'));
 assert.ok(!csv.includes('undefined'));
 await p.locator('[data-x=backup]').click();
 const backup=await p.evaluate(()=>JSON.parse(decodeURIComponent(escape(atob(saves.at(-1).content)))));
 assert.equal(backup.data['balans2.manual'].weight.rec[0].v,82.4);
 assert.ok(await p.evaluate(o=>validateBackup(o),backup));
 await p.evaluate(()=>{onStorageError();onStorageError()});
 assert.equal(await p.locator('#storageWarning').count(),1);
 assert.ok(await p.locator('#storageWarning').isVisible());
 await p.reload();
 assert.equal(await p.evaluate('recs(byId.weight).at(-1).v'),82.4);
 assert.equal(await p.evaluate('recs(byId.bp).at(-1).lo'),81);
 assert.deepEqual(errors,[]);
 console.log('PASS: manual current timestamp/validation/BP pair, partial HC revocation preserves BLE/manual, cancelled snapshot preserved, CSV actual sources, backup JSON, inline storage warning, reload.');
 await b.close();
})().catch(e=>{console.error(e);process.exit(1)});
